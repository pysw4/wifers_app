def _normalize_text(text: str) -> str:
    """Normalize text by removing diacritics (accents) and converting to lowercase."""
    import unicodedata
    # Normalize to NFKD form which separates base characters from diacritics
    nfkd = unicodedata.normalize('NFKD', text)
    # Remove combining diacritical marks (accents, cedillas, etc.)
    return ''.join(c for c in nfkd if not unicodedata.combining(c)).lower()


def _encode_building(building_name: str) -> int:
    encoder = _load_building_encoder()
    meta = _load_signal_strength_meta()
    buildings_list = meta.get("buildings", [])
    if encoder is not None and building_name in encoder.classes_:
        return int(encoder.transform([building_name])[0])
    # Try exact match with encoder classes (case-insensitive)
    if encoder is not None:
        for cls in encoder.classes_:
            if building_name.lower() == cls.lower():
                return int(encoder.transform([cls])[0])
    # Try fuzzy match with buildings_list
    norm_building = _normalize_text(building_name)
    for i, b in enumerate(buildings_list):
        norm_b = _normalize_text(b)
        if norm_building in norm_b or norm_b in norm_building:
            return i
    # Try fuzzy match with encoder classes
    if encoder is not None:
        for i, cls in enumerate(encoder.classes_):
            norm_cls = _normalize_text(cls)
            if norm_building in norm_cls or norm_cls in norm_building:
                return i
    return 0


def _dbm_to_quality(dbm: float) -> dict:
    if dbm >= -50:
        return {"quality": "Excellent", "bars": 5}
    elif dbm >= -60:
        return {"quality": "Good", "bars": 4}
    elif dbm >= -70:
        return {"quality": "Fair", "bars": 3}
    elif dbm >= -80:
        return {"quality": "Weak", "bars": 2}
    else:
        return {"quality": "Very Poor", "bars": 1}


def _dbm_to_status(dbm: float) -> str:
    """Convert signal dBm to predicted Up/Down status.
    Signal >= -75 dBm → likely Up (usable connection)
    Signal < -75 dBm → likely Down (too weak for reliable use)
    """
    return "Up" if dbm >= -75 else "Down"


def _dbm_to_status_confidence(dbm: float) -> float:
    """Confidence of the status prediction based on how far from threshold."""
    # -75 dBm threshold, confidence scales with distance from threshold
    diff = dbm - (-75)
    # Clamp confidence between 0.5 and 0.99
    confidence = min(0.99, max(0.5, 0.5 + abs(diff) / 50))
    return round(confidence, 3)


def _smooth_series(values: list, window: int = 3) -> list:
    n = len(values)
    if n < 3 or window < 3:
        return list(values)
    if window == 3:
        weights = [0.25, 0.5, 0.25]
    elif window == 5:
        weights = [0.1, 0.2, 0.4, 0.2, 0.1]
    else:
        half = window // 2
        weights = []
        for i in range(window):
            w = 1.0 - abs(i - half) / (half + 1)
            weights.append(w)
        total = sum(weights)
        weights = [w / total for w in weights]
    half = len(weights) // 2
    smoothed = []
    for i in range(n):
        total_w = 0.0
        total_v = 0.0
        for j, w in enumerate(weights):
            idx = i + j - half
            if 0 <= idx < n:
                total_w += w
                total_v += w * values[idx]
        smoothed.append(total_v / total_w if total_w > 0 else values[i])
    return smoothed


def _smooth_actual_hourly(hourly_dict: dict, min_samples: int = 20) -> dict:
    if not hourly_dict:
        return hourly_dict
    raw_values = []
    sample_counts = []
    for h in range(24):
        if h in hourly_dict:
            raw_values.append(hourly_dict[h]["actual_mean"])
            sample_counts.append(hourly_dict[h]["samples"])
        else:
            raw_values.append(None)
            sample_counts.append(0)
    filled = list(raw_values)
    known_indices = [i for i, v in enumerate(filled) if v is not None]
    if len(known_indices) >= 2:
        for h in range(24):
            if filled[h] is None:
                before = [i for i in known_indices if i < h]
                after = [i for i in known_indices if i > h]
                if before and after:
                    hb, ha = before[-1], after[0]
                    ratio = (h - hb) / (ha - hb)
                    filled[h] = filled[hb] + (filled[ha] - filled[hb]) * ratio
                elif before:
                    filled[h] = filled[before[-1]]
                elif after:
                    filled[h] = filled[after[0]]
    elif len(known_indices) == 1:
        v = filled[known_indices[0]]
        filled = [v] * 24
    smoothed_filled = list(filled)
    for h in range(24):
        if hourly_dict.get(h, {}).get("samples", 0) < min_samples and sample_counts[h] > 0:
            neighbor_weight = min(0.8, 1.0 - sample_counts[h] / min_samples)
            neighbor_sum = 0
            neighbor_count = 0
            for dh in [-2, -1, 1, 2]:
                nh = h + dh
                if 0 <= nh < 24 and filled[nh] is not None:
                    neighbor_sum += filled[nh]
                    neighbor_count += 1
            if neighbor_count > 0:
                neighbor_avg = neighbor_sum / neighbor_count
                smoothed_filled[h] = filled[h] * (1 - neighbor_weight) + neighbor_avg * neighbor_weight
    smoothed_values = _smooth_series(smoothed_filled, window=3)
    smoothed_values = _smooth_series(smoothed_values, window=3)
    result = {}
    for h in range(24):
        result[h] = {
            "actual_mean": round(smoothed_values[h], 1),
            "samples": sample_counts[h],
            "interpolated": raw_values[h] is None,
            "smoothed": sample_counts[h] < min_samples,
        }
    return result


def _haversine_distance(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    R = 6371000
    dlat = math.radians(lat2 - lat1)
    dlng = math.radians(lng2 - lng1)
    a = (math.sin(dlat / 2) ** 2 + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.sin(dlng / 2) ** 2)
    c = 2 * math.asin(math.sqrt(a))
    return R * c


def _approximate_distance(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    lat_diff = (lat2 - lat1) * 111_320
    lng_diff = (lng2 - lng1) * 111_320 * abs(math.cos(math.radians((lat1 + lat2) / 2)))
    return math.sqrt(lat_diff ** 2 + lng_diff ** 2)


