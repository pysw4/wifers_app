def _generate_alternative_paths(lat: float, lng: float, dest_lat: float, dest_lng: float, acceptable_range: int = 500) -> list[dict]:
    """Generate alternative routes by using different waypoints."""
    graph = _load_light_route_graph()
    nodes = graph["nodes"]
    edges = graph["edges"]

    adj: dict[str, list[tuple[str, float]]] = {}
    for u, v, length in edges:
        adj.setdefault(u, []).append((v, length))
        adj.setdefault(v, []).append((u, length))

    def nearest_node(lat: float, lng: float) -> str | None:
        best_id = None
        best_dist = float("inf")
        for nid, ndata in nodes.items():
            d = _haversine_distance(lat, lng, ndata["lat"], ndata["lng"])
            if d < best_dist:
                best_dist = d
                best_id = nid
        return best_id

    start_node = nearest_node(lat, lng)
    dest_node = nearest_node(dest_lat, dest_lng)
    if start_node is None or dest_node is None:
        return []

    def dijkstra_to_all(from_node: str) -> tuple[dict[str, float], dict[str, str | None]]:
        dists: dict[str, float] = {from_node: 0}
        prevs: dict[str, str | None] = {from_node: None}
        pq: list[tuple[float, str]] = [(0, from_node)]
        while pq:
            d, u = heapq.heappop(pq)
            if d > dists.get(u, float("inf")):
                continue
            for v, w in adj.get(u, []):
                nd = d + w
                if nd < dists.get(v, float("inf")):
                    dists[v] = nd
                    prevs[v] = u
                    heapq.heappush(pq, (nd, v))
        return dists, prevs

    def reconstruct_path(prevs: dict, target: str) -> list[dict]:
        path_nodes: list[str] = []
        u: str | None = target
        while u is not None:
            path_nodes.append(u)
            u = prevs.get(u)
        path_nodes.reverse()
        return [{"lat": nodes[nid]["lat"], "lng": nodes[nid]["lng"]} for nid in path_nodes]

    # Forward distances from start
    dists_from_start, _ = dijkstra_to_all(start_node)
    # Backward distances to dest
    dists_to_dest, prevs_to_dest = dijkstra_to_all(dest_node)

    if dest_node not in dists_from_start:
        return []

    shortest_dist = dists_from_start[dest_node]

    # Find intermediate nodes that are "reasonable" deviations
    alternatives = []
    # Pick 2-3 candidate waypoints that are within 30-60% along the path
    candidates = []
    for nid, ndata in nodes.items():
        if nid == start_node or nid == dest_node:
            continue
        if nid not in dists_from_start or nid not in dists_to_dest:
            continue
        via_dist = dists_from_start[nid] + dists_to_dest[nid]
        # Only consider routes that are at most 1.5x the shortest path
        if via_dist <= shortest_dist * 1.5 and via_dist > shortest_dist * 1.05:
            candidates.append((nid, via_dist))

    # Sort by distance (closest to shortest first)
    candidates.sort(key=lambda x: x[1])
    
    # Take 2-3 best candidates, ensuring diversity (different branches)
    used_paths: set[str] = set()
    for nid, _ in candidates[:5]:
        if len(alternatives) >= 3:
            break
        path = reconstruct_path(prevs_to_dest, nid)
        path_key = str([(p["lat"], p["lng"]) for p in path[:3]])
        if path_key in used_paths:
            continue
        used_paths.add(path_key)
        
        alt_distance = dists_from_start.get(nid, 0) + dists_to_dest.get(nid, 0)
        if alt_distance > 0:
            alternatives.append({
                "path": path,
                "distance": round(alt_distance, 1),
            })

    return alternatives


@app.post("/foto2ap/recognize")
async def foto2ap_recognize(file: UploadFile = File(...)):
    """
    Upload a photo of an AP access point and recognise its name + location.

    Uses PaddleOCR to extract text from the image, parses the AP code,
    and looks up its coordinates in the GeoJSON database.

    Returns:
        {
            "success": true,
            "ap_name": "AP-ETSE58",
            "lat": 41.5004,
            "lng": 2.1129,
            "building": "ETSE",
            "floor": 0,
            "espacio": "..."
        }
    """
    if not file.content_type or not file.content_type.startswith("image/"):
        raise HTTPException(status_code=400, detail="File must be an image")

    try:
        image_bytes = await file.read()
        if len(image_bytes) == 0:
            raise HTTPException(status_code=400, detail="Empty file")
    except Exception:
        raise HTTPException(status_code=400, detail="Failed to read uploaded file")

    try:
        from foto2ap_service import recognize_ap
        result = recognize_ap(image_bytes)
    except ImportError as e:
        raise HTTPException(status_code=503, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"OCR recognition failed: {str(e)}")

    if result is None:
        return JSONResponse(
            status_code=404,
            content={"success": False, "message": "No AP could be recognised in the image. Try a clearer photo of the AP label."}
        )

    return {"success": True, **result}


