def _build_ap_index() -> list[dict]:
    global _ap_index, _ap_index_by_name
    if _ap_index is not None:
        return _ap_index
    geojson = _load_geojson()
    _ap_index = []
    _ap_index_by_name = {}
    seen_ids = {}
    for feature in geojson["features"]:
        props = feature["properties"]
        coords = feature["geometry"]["coordinates"]
        ap_name = props.get("USER_NOM_A", "Unknown")
        espacio = props.get("USER_Espai", "")
        # Build a unique ID from AP name + espacio (room code)
        unique_id = f"{ap_name}_{espacio}" if espacio else ap_name
        # Handle duplicate AP names by appending a counter
        if unique_id in seen_ids:
            seen_ids[unique_id] += 1
            unique_id = f"{unique_id}_{seen_ids[unique_id]}"
        else:
            seen_ids[unique_id] = 0
        _ap_index.append({
            "id": unique_id,
            "name": ap_name,
            "lat": float(coords[1]),
            "lng": float(coords[0]),
            "building": props.get("USER_EDIFI", props.get("Nom_Edific", "Unknown")),
            "floor": float(props.get("Num_Planta", 0) or 0),
            "espacio": espacio,
        })
        # Build O(1) lookup
        ap_key = ap_name.strip().lower()
        if ap_key not in _ap_index_by_name:
            _ap_index_by_name[ap_key] = _ap_index[-1]
    return _ap_index


def _get_buildings_list() -> list[str]:
    global _buildings_list
    if _buildings_list is not None:
        return _buildings_list
    index = _build_ap_index()
    buildings = sorted({ap["building"] for ap in index if ap["building"] != "Unknown"})
    _buildings_list = buildings
    return _buildings_list


def _validate_day(day: str) -> str:
    day_lower = day.strip().lower()
    if day_lower in DAY_NAMES:
        return day_lower
