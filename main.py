def _find_route_path(lat: float, lng: float, dest_lat: float, dest_lng: float, acceptable_range: int = 500) -> dict:
    """
    Find a walking path on the UAB campus road graph using pure Python Dijkstra.
    No osmnx, no networkx — just a JSON file and heapq (< 1 MB memory).
    """
    graph = _load_light_route_graph()
    nodes = graph["nodes"]
    edges = graph["edges"]

    # Build adjacency list
    adj: dict[str, list[tuple[str, float]]] = {}
    for u, v, length in edges:
        adj.setdefault(u, []).append((v, length))
        adj.setdefault(v, []).append((u, length))

    def nearest_node(lat: float, lng: float) -> str:
        best_id = None
        best_dist = float("inf")
        for nid, ndata in nodes.items():
            d = _haversine_distance(lat, lng, ndata["lat"], ndata["lng"])
            if d < best_dist:
                best_dist = d
                best_id = nid
        return best_id

    start_node = nearest_node(lat, lng)
    dest_node = nearest_node(dest_lat, dest_lng)

    if start_node is None or dest_node is None:
        return {"path": [], "distance": 0, "waypoints": [], "total_waypoints": 0}

    # Pure Python Dijkstra
    distances: dict[str, float] = {start_node: 0}
    prev: dict[str, str | None] = {start_node: None}
    pq: list[tuple[float, str]] = [(0, start_node)]

    while pq:
        d, u = heapq.heappop(pq)
        if u == dest_node:
            break
        if d > distances.get(u, float("inf")):
            continue
        for v, w in adj.get(u, []):
            nd = d + w
            if nd < distances.get(v, float("inf")):
                distances[v] = nd
                prev[v] = u
                heapq.heappush(pq, (nd, v))

    if dest_node not in distances or distances[dest_node] == float("inf"):
        return {"path": [], "distance": 0, "waypoints": [], "total_waypoints": 0}

    path_nodes: list[str] = []
    u: str | None = dest_node
    while u is not None:
        path_nodes.append(u)
        u = prev.get(u)
    path_nodes.reverse()

    path_coords = []
    for nid in path_nodes:
        nd = nodes[nid]
        path_coords.append({"lat": nd["lat"], "lng": nd["lng"]})

    # Find APs near start/dest as waypoints (same as before)
    ap_index = _build_ap_index()
    path_aps = []
    for ap in ap_index:
        dist_to_start = _approximate_distance(lat, lng, ap["lat"], ap["lng"])
        dist_to_dest = _approximate_distance(dest_lat, dest_lng, ap["lat"], ap["lng"])
        if dist_to_start <= acceptable_range or dist_to_dest <= acceptable_range:
            path_aps.append({
                "lat": ap["lat"], "lng": ap["lng"],
                "building": ap["building"], "floor": int(ap["floor"]),
                "ap_name": ap["name"],
                "distance_to_start": round(dist_to_start, 1),
                "distance_to_dest": round(dist_to_dest, 1),
            })

    return {
        "path": path_coords,
        "distance": round(distances[dest_node], 1),
        "waypoints": path_aps,
        "total_waypoints": len(path_aps),
    }


